/** Distance en km entre deux points (formule de haversine). */
export function distanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) ** 2 + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

/** Trouve la commune algérienne la plus proche d'une position GPS (null si hors d'Algérie). */
export function findNearestAlgerianCommune(lat: number, lng: number) {
  // Rectangle englobant approximatif de l'Algérie
  const inBox = lat >= 18.9 && lat <= 37.3 && lng >= -8.7 && lng <= 12.0;
  if (!inBox) return null;

  let best: { wilaya: AlgeriaWilaya; commune: AlgeriaWilaya['communes'][number]; km: number } | null = null;
  for (const wilaya of ALGERIA_WILAYAS) {
    for (const commune of wilaya.communes) {
      const km = distanceKm(lat, lng, commune.latitude, commune.longitude);
      if (!best || km < best.km) best = { wilaya, commune, km };
    }
  }
  return best && best.km <= 250 ? best : null;
}
